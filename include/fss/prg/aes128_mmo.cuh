#pragma once
#include <fss/prg.cuh>
#include <cuda_runtime.h>
#include <cuda/std/array>
#include <cuda/std/span>
#include <cassert>
#include <openssl/evp.h>
#include <openssl/aes.h>
#include <fss/util.cuh>

namespace fss::prg {

/**
 * Declared and never defined. Device code that reaches it fails to link with an
 * unresolved-extern error that names this symbol.
 */
__device__ void fss_host_only_Aes128Mmo_used_in_device_code();

/**
 * AES-128 with Matyas-Meyer-Oseas and pre-initialized cipher contexts as a PRG.
 *
 * Host-only. Device use of Gen() or GenHalf() fails to build with an
 * unresolved-extern error naming `fss_host_only_Aes128Mmo_used_in_device_code`.
 *
 * Concurrency: Gen() runs EVP_EncryptUpdate on the ctxs, and copies of an instance
 * share the same ctxs. OpenSSL does not document one ctx as safe for concurrent
 * updates even for full-block no-padding ECB, so Gen() must not run concurrently
 * on instances sharing ctxs. Parallel host evaluation needs a PRG whose Gen() is
 * safe to call concurrently, such as ChaCha or Aes128MmoRaw.
 *
 * @tparam mul See Prgable mul.
 */
template <int mul>
class Aes128Mmo {
public:
  /**
     * Constructor.
     *
     * @param ctxs Generated by CreateCtxs() and freed by FreeCtxs().
     * Copies borrow the same mutable contexts. Concurrent Gen() calls require
     * distinct contexts.
     * Users are responsible for managing their lifetime.
     */
  Aes128Mmo(cuda::std::span<EVP_CIPHER_CTX *, mul> ctxs);

  /**
     * Create cipher contexts.
     *
     * @param keys mul 16B AES-128 keys.
     */
  static cuda::std::array<EVP_CIPHER_CTX *, mul> CreateCtxs(const unsigned char *keys[mul]);

  static void FreeCtxs(cuda::std::span<EVP_CIPHER_CTX *, mul> ctxs);

  __host__ __device__ cuda::std::array<int4, mul> Gen(int4 seed);

  /**
   * Return the selected half of Gen() with the same call requirements.
   *
   * @param right false selects the first half, true selects the second half.
   */
  __host__ __device__ cuda::std::array<int4, mul / 2> GenHalf(int4 seed, bool right)
    requires(mul > 0 && mul % 2 == 0);

private:
  cuda::std::array<EVP_CIPHER_CTX *, mul> ctxs_;
};
// -----------------------------------------------------------------------------

template <int mul>
inline Aes128Mmo<mul>::Aes128Mmo(cuda::std::span<EVP_CIPHER_CTX *, mul> ctxs) {
  for (int i = 0; i < mul; ++i) ctxs_[i] = ctxs[i];
}

template <int mul>
inline cuda::std::array<EVP_CIPHER_CTX *, mul> Aes128Mmo<mul>::CreateCtxs(const unsigned char *keys[mul]) {
  int ret;
  cuda::std::array<EVP_CIPHER_CTX *, mul> ctxs;

  for (int i = 0; i < mul; ++i) {
    ctxs[i] = EVP_CIPHER_CTX_new();
    assert(ctxs[i] != NULL);

    ret = EVP_EncryptInit_ex2(ctxs[i], EVP_aes_128_ecb(), keys[i], NULL, NULL);
    assert(ret == 1);

    ret = EVP_CIPHER_CTX_set_padding(ctxs[i], 0);
    assert(ret == 1);
  }
  return ctxs;
}

template <int mul>
inline void Aes128Mmo<mul>::FreeCtxs(cuda::std::span<EVP_CIPHER_CTX *, mul> ctxs) {
  for (auto ctx : ctxs) {
    EVP_CIPHER_CTX_free(ctx);
  }
}

template <int mul>
__host__ __device__ inline cuda::std::array<int4, mul> Aes128Mmo<mul>::Gen(int4 seed) {
  cuda::std::array<int4, mul> out{};

#ifdef __CUDA_ARCH__
  fss_host_only_Aes128Mmo_used_in_device_code();
#else
  for (int i = 0; i < mul; ++i) {
    auto out_ptr = reinterpret_cast<unsigned char *>(&out[i]);
    auto seed_ptr = reinterpret_cast<const unsigned char *>(&seed);
    int cipher_len = 0;
    int ret = EVP_EncryptUpdate(ctxs_[i], out_ptr, &cipher_len, seed_ptr, AES_BLOCK_SIZE);
    assert(ret == 1);
    assert(cipher_len == AES_BLOCK_SIZE);

    out[i] = fss::util::Xor(out[i], seed);
  }
#endif

  return out;
}

template <int mul>
__host__ __device__ inline cuda::std::array<int4, mul / 2> Aes128Mmo<mul>::GenHalf(int4 seed, bool right)
  requires(mul > 0 && mul % 2 == 0)
{
  cuda::std::array<int4, mul / 2> out{};

#ifdef __CUDA_ARCH__
  fss_host_only_Aes128Mmo_used_in_device_code();
#else
  int offset = right ? mul / 2 : 0;
  for (int i = 0; i < mul / 2; ++i) {
    auto out_ptr = reinterpret_cast<unsigned char *>(&out[i]);
    auto seed_ptr = reinterpret_cast<const unsigned char *>(&seed);
    int cipher_len = 0;
    int ret = EVP_EncryptUpdate(ctxs_[i + offset], out_ptr, &cipher_len, seed_ptr, AES_BLOCK_SIZE);
    assert(ret == 1);
    assert(cipher_len == AES_BLOCK_SIZE);

    out[i] = fss::util::Xor(out[i], seed);
  }
#endif

  return out;
}

static_assert(Prgable<Aes128Mmo<2>, 2> && Prgable<Aes128Mmo<4>, 4>);

}  // namespace fss::prg
